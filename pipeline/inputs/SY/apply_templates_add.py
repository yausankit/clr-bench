"""Append ADD_SY_a1 rule templates to scenario.yaml and list them in chains/SY5.yaml.

One template per new list; its rule names exactly that list's SNOMED parent class.  Existing
templates and the other chain configs are left byte for byte unchanged.  Deterministic.
"""
import csv
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent
PLAUSIBLE = {
    "snomed_386637004": ["snomed_386637004", "mesh_e_e04_520_obstetric_surgical_procedures",
                         "snomed_118675001"],
    "snomed_118675001": ["snomed_118675001", "snomed_386637004",
                         "mesh_e_e04_surgical_procedures_operative"],
    "snomed_20135006": ["snomed_20135006", "mesh_e_e01_370_diagnostic_techniques_and_procedures",
                        "mesh_e_e05_investigative_techniques"],
    "snomed_413815006": ["snomed_413815006", "mesh_e_e01_370_350_diagnostic_imaging",
                         "snomed_16310003"],
    "snomed_252318005": ["snomed_252318005", "mesh_e_e05_478_immunologic_techniques",
                         "mesh_e_e01_370_225_clinical_laboratory_techniques"],
    "snomed_59108006": ["snomed_59108006", "mesh_e_e02_therapeutics", "snomed_18629005"],
    "snomed_118797008": ["snomed_118797008", "mesh_e_e04_surgical_procedures_operative",
                         "snomed_276341003"],
    "snomed_118838009": ["snomed_118838009", "mesh_e_e01_370_388_diagnostic_techniques_surgical",
                         "snomed_284366008"],
    "snomed_392089008": ["snomed_392089008", "snomed_86273004", "snomed_16310003"],
    "snomed_18629005": ["snomed_18629005", "mesh_e_e02_therapeutics", "snomed_59108006"],
    "snomed_305056002": ["snomed_305056002", "snomed_14734007", "mesh_e_e02_therapeutics"],
    "snomed_276341003": ["snomed_276341003", "mesh_e_e01_370_350_diagnostic_imaging",
                         "snomed_118797008"],
    "snomed_284366008": ["snomed_284366008", "snomed_5880005",
                         "mesh_e_e01_370_diagnostic_techniques_and_procedures"],
}
MARK = "# --- ADD_SY_a1 procedure templates below (generated by apply_templates_add.py) ---"


def main():
    spec = list(csv.DictReader((ROOT / "add_lists_spec.tsv").open(encoding="utf-8"), delimiter="\t"))
    templates = []
    for i, row in enumerate(spec):
        tid = f"procedure_rule_{17 + i}"
        templates.append({
            "id": tid,
            "field": "procedures.code",
            "effect": "exclude_record",
            "source": f"supplement: the health plan's audit lane names {row['name']}",
            "rule": f"A procedure whose code belongs to {row['name']} is not counted.",
            "plausible": PLAUSIBLE[row["id"]],
        })
    scen = ROOT / "scenario.yaml"
    text = scen.read_text(encoding="utf-8")
    if "\nlabel_nouns:" not in text:
        raise SystemExit("scenario.yaml: no label_nouns anchor")
    head = text[:text.index("\nlabel_nouns:")]
    if MARK in head:
        head = head[:head.index(MARK)]
    tail = text[text.index("\nlabel_nouns:"):]
    block = MARK + "\n" + yaml.safe_dump(templates, allow_unicode=True, sort_keys=False)
    scen.write_text(head.rstrip() + "\n" + block + "label_nouns:" + tail.split("label_nouns:", 1)[1], encoding="utf-8")

    chain = ROOT / "chains" / "SY5.yaml"
    ctext = chain.read_text(encoding="utf-8")
    anchor = "  - procedure_rule_16\n"
    if anchor not in ctext:
        raise SystemExit("chains/SY5.yaml: procedure_rule_16 anchor missing")
    add = "".join(f"  - {t['id']}\n" for t in templates)
    if add in ctext:
        pass
    else:
        ctext = ctext.replace(anchor, anchor + add, 1)
        chain.write_text(ctext, encoding="utf-8")
    print(f"scenario.yaml: {len(templates)} templates; chains/SY5.yaml updated")


if __name__ == "__main__":
    main()
