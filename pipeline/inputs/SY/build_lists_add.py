"""Append the ADD_SY_a1 procedure lists to lists/procedure.yaml.

Each list is a closed SNOMED CT parent class: the members are the is-a expansion entries
(`raw/snomed/expand_<code>.json`) that are values of universes/procedure.tsv.  The expansion's
other entries go to out_of_universe, so members + disputed + out_of_universe == official_count.
Existing entries are never rewritten: everything before the marker line is kept byte for byte.

Deterministic: run twice, the output is identical.
"""
import csv
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent
MARK = "# --- ADD_SY_a1 lists below (generated by build_lists_add.py) ---"


def spec():
    with (ROOT / "add_lists_spec.tsv").open(encoding="utf-8") as fh:
        return list(csv.DictReader(fh, delimiter="\t"))


def universe():
    path = ROOT / "universes" / "procedure.tsv"
    with path.open(encoding="utf-8") as fh:
        return {r["value"]: r["entity"] for r in csv.DictReader(fh, delimiter="\t")}


def salience():
    path = ROOT / "salience" / "procedure.tsv"
    out = {}
    if path.exists():
        with path.open(encoding="utf-8") as fh:
            for r in csv.DictReader(fh, delimiter="\t"):
                try:
                    out[r["concept_id"]] = int(float(r.get("pageviews_12m") or 0))
                except ValueError:
                    out[r["concept_id"]] = 0
    return out


def main():
    vals = universe()
    sal = salience()
    rows = []
    for row in spec():
        code = row["code"]
        data = yaml.safe_load((ROOT / "raw" / "snomed" / f"expand_{code}.json").read_text())
        exp = data["expansion"]
        contains = exp["contains"]
        total = exp.get("total")
        if total is None or total != len(contains):
            raise SystemExit(f"expand_{code}.json: expansion is truncated ({total} vs {len(contains)})")
        members = sorted({x["code"] for x in contains} & set(vals))
        member_set = set(members)
        oou = sorted({x["display"] for x in contains if x["code"] not in member_set})
        got = len(members) + len(oou)
        if got != total:
            raise SystemExit(f"expand_{code}.json: members+out_of_universe={got} != official_count {total} "
                             f"(duplicate displays in the expansion)")
        rows.append({
            "id": row["id"],
            "name": row["name"],
            "synonyms": [],
            "members": members,
            "disputed": [],
            "changes": [],
            "official_count": total,
            "out_of_universe": oou,
            "source": f"SNOMED CT International Edition is-a descendants of {code} "
                      f"({row['name']}) (tx.fhir.org/r4 ValueSet/$expand)",
            "salience": sal.get(row["id"], 0),
        })
    path = ROOT / "lists" / "procedure.yaml"
    text = path.read_text(encoding="utf-8")
    if MARK in text:
        text = text[:text.index(MARK)].rstrip() + "\n"
    if not text.endswith("\n"):
        text += "\n"
    block = MARK + "\n" + yaml.safe_dump(rows, allow_unicode=True, sort_keys=False)
    path.write_text(text + block, encoding="utf-8")
    print(f"lists/procedure.yaml: {len(rows)} added lists")


if __name__ == "__main__":
    main()
