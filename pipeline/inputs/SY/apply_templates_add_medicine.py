"""Append ADD_SY_a2 medicine rule templates to scenario.yaml and list them in chains/SY5.yaml.

One template per new list; its rule names exactly that list.  The two other plausible lists are
the strongest-overlapping lists whose member sets differ from the new list.  Existing templates
and chains SY1-SY4 are left byte for byte unchanged.
"""
import csv
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent
MARK = "# --- ADD_SY_a2 medicine templates below (generated by apply_templates_add_medicine.py) ---"
MARK_PREFIX = "# --- ADD_SY_a2 medicine templates below"
FIRST = 35


def main():
    spec = list(csv.DictReader((ROOT / "add_lists_spec_medicine.tsv").open(encoding="utf-8"), delimiter="\t"))
    lists = yaml.safe_load((ROOT / "lists" / "medicine.yaml").read_text(encoding="utf-8"))
    by_id = {r["id"]: r for r in lists}
    sets = {r["id"]: frozenset(r["members"]) for r in lists}
    templates = []
    for i, row in enumerate(spec):
        target = row["id"]
        ts = sets[target]
        ranked = []
        for lid, s in sets.items():
            if lid == target or s == ts:
                continue
            overlap = len(ts & s)
            if overlap:
                ranked.append((-overlap, -by_id[lid].get("salience", 0), lid))
        ranked.sort()
        other = [lid for _, _, lid in ranked[:2]]
        if len(other) < 2:
            raise SystemExit(f"{target}: fewer than two overlapping lists")
        templates.append({
            "id": f"medicine_rule_{FIRST + i}",
            "field": "medications.ingredient",
            "effect": "exclude_record",
            "source": f"supplement: the health plan's audit lane names {row['name']}",
            "rule": f"A medication whose ingredient belongs to {row['name']} is not counted.",
            "plausible": [target] + other,
        })
        print(target, "->", other)
    scen = ROOT / "scenario.yaml"
    text = scen.read_text(encoding="utf-8")
    if "\nlabel_nouns:" not in text:
        raise SystemExit("scenario.yaml: no label_nouns anchor")
    head = text[:text.index("\nlabel_nouns:")]
    if MARK_PREFIX in head:
        head = head[:head.index(MARK_PREFIX)]
    tail = text[text.index("\nlabel_nouns:"):]
    block = MARK + "\n" + yaml.safe_dump(templates, allow_unicode=True, sort_keys=False)
    scen.write_text(head.rstrip() + "\n" + block + "label_nouns:" + tail.split("label_nouns:", 1)[1],
                    encoding="utf-8")

    chain = ROOT / "chains" / "SY5.yaml"
    ctext = chain.read_text(encoding="utf-8")
    anchor = "  - medicine_rule_34\n"
    if anchor not in ctext:
        raise SystemExit("chains/SY5.yaml: medicine_rule_34 anchor missing")
    add = "".join(f"  - {t['id']}\n" for t in templates)
    if add not in ctext:
        ctext = ctext.replace(anchor, anchor + add, 1)
        chain.write_text(ctext, encoding="utf-8")
    print(f"scenario.yaml: {len(templates)} templates; chains/SY5.yaml updated")


if __name__ == "__main__":
    main()
