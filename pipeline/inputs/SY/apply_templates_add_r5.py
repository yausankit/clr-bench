#!/usr/bin/env python3
"""Append ADD_SY_a5 medicine rule templates and add them to all five chains."""
import csv
import re
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent
MARK = "# --- ADD_SY_a5 medicine templates below (generated by apply_templates_add_r5.py) ---"
MARK_PREFIX = "# --- ADD_SY_a5 medicine templates below"
FIRST = 47


def add_to_chain(path, template_ids):
    text = path.read_text(encoding="utf-8")
    addition = "".join(f"  - {template_id}\n" for template_id in template_ids)
    if addition in text:
        return
    matches = list(re.finditer(r"^  - medicine_rule_[0-9]+\n", text, flags=re.MULTILINE))
    if not matches:
        raise SystemExit(f"{path}: no medicine rule anchor")
    anchor = matches[-1]
    path.write_text(text[:anchor.end()] + addition + text[anchor.end():], encoding="utf-8")


def main():
    with (ROOT / "add_lists_spec_r5.tsv").open(encoding="utf-8") as handle:
        spec = list(csv.DictReader(handle, delimiter="\t"))
    lists = yaml.safe_load((ROOT / "lists" / "medicine.yaml").read_text(encoding="utf-8"))
    by_id = {row["id"]: row for row in lists}
    sets = {row["id"]: frozenset(row["members"]) for row in lists}
    templates = []
    for index, row in enumerate(spec):
        target = row["id"]
        target_set = sets[target]
        ranked = []
        for list_id, members in sets.items():
            if list_id == target or members == target_set:
                continue
            overlap = len(target_set & members)
            if overlap:
                ranked.append((-overlap, -by_id[list_id].get("salience", 0), list_id))
        ranked.sort()
        alternatives = [list_id for _, _, list_id in ranked[:2]]
        if len(alternatives) < 2:
            raise SystemExit(f"{target}: fewer than two overlapping lists")
        templates.append({
            "id": f"medicine_rule_{FIRST + index}",
            "field": "medications.ingredient",
            "effect": "exclude_record",
            "source": f"supplement: the health plan's audit lane names {row['name']}",
            "rule": f"A medication whose ingredient belongs to {row['name']} is not counted.",
            "plausible": [target] + alternatives,
        })
        print(target, "->", alternatives)

    scenario_path = ROOT / "scenario.yaml"
    text = scenario_path.read_text(encoding="utf-8")
    marker = "\nlabel_nouns:"
    if marker not in text:
        raise SystemExit("scenario.yaml: no label_nouns anchor")
    head = text[:text.index(marker)]
    if MARK_PREFIX in head:
        head = head[:head.index(MARK_PREFIX)]
    tail = text[text.index(marker):]
    block = MARK + "\n" + yaml.safe_dump(templates, allow_unicode=True, sort_keys=False)
    scenario_path.write_text(head.rstrip() + "\n" + block + "label_nouns:" +
                            tail.split("label_nouns:", 1)[1], encoding="utf-8")

    template_ids = [template["id"] for template in templates]
    for chain_name in ("SY1", "SY2", "SY3", "SY4", "SY5"):
        add_to_chain(ROOT / "chains" / f"{chain_name}.yaml", template_ids)
    print(f"scenario.yaml: {len(templates)} templates; chains SY1-SY5 updated")


if __name__ == "__main__":
    main()
