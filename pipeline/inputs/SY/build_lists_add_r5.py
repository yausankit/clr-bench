#!/usr/bin/env python3
"""Append the ADD_SY_a5 medicine lists to lists/medicine.yaml.

The official terms and their raw-source evidence are read from the manifest
created by extract_manifest_add_r5.py.  Existing list entries are preserved
byte for byte up to the new marker.
"""
import csv
import json
import re
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent
RAW = ROOT / "raw" / "add" / "r5"
MANIFEST = RAW / "manifests" / "official_members.json"
MARK = "# --- ADD_SY_a5 medicine lists below (generated by build_lists_add_r5.py) ---"
MARK_PREFIX = "# --- ADD_SY_a5 medicine lists below"

TOKEN_ALIASES = {
    "paracetamol": "acetaminophen", "pethidine": "meperidine",
    "norethisterone": "norethindrone", "phenoxymethylpenicillin": "penicillin",
    "clavulanic": "clavulanate", "ethinylestradiol": "ethinyl",
    "leuprorelin": "leuprolide", "adrenaline": "epinephrine", "salbutamol": "albuterol",
    "ciclosporin": "cyclosporine", "frusemide": "furosemide", "lignocaine": "lidocaine",
}

WHOLE_ALIASES = {
    "clavulanic acid": "clavulanate",
    "calcium folinate (leucovorin calcium)": "leucovorin",
    "medroxyprogesterone acetate": "medroxyprogesterone",
}

IGNORE = {
    "hydrochloride", "hcl", "hydrobromide", "hbr", "sulfate", "sulphate", "phosphate",
    "diphosphate", "tartrate", "bitartrate", "maleate", "mesylate", "besylate", "tosylate",
    "acetate", "succinate", "fumarate", "citrate", "lactate", "carbonate", "bicarbonate",
    "chloride", "bromide", "iodide", "nitrate", "nitrite", "oxide", "hydroxide", "anhydrous",
    "dihydrate", "monohydrate", "hemihydrate", "hydrate", "sodium", "potassium", "calcium",
    "magnesium", "tromethamine", "trometamol", "pamoate", "palmitate", "decanoate", "enantate",
    "acetonide", "furoate", "dipivoxil", "edisylate", "embonate", "hyclate", "mononitrate",
    "dinitrate", "base", "tablet", "tablets", "capsule", "capsules", "injection", "injectable",
    "solution", "suspension", "oral", "extended", "release", "delayed", "immediate", "er", "xr",
    "sr", "cr", "cream", "gel", "ointment", "topical", "ophthalmic", "inhalation", "spray",
    "powder", "granule", "granules", "concentrate", "infusion", "vial", "prefilled", "syringe",
    "usp", "micronized", "sterile", "aqueous", "film", "coated", "chewable", "dispersible",
    "and", "with", "as", "eq", "equivalent", "unit", "units", "mg", "ml",
}


def name_key(name):
    text = re.sub(r"\s+", " ", str(name).lower().replace("-", " ")).strip()
    text = re.sub(r"\([^)]*\)", " ", text)
    for old, new in WHOLE_ALIASES.items():
        text = text.replace(old, new)
    text = text.replace("&", " and ").replace("+", " and ").replace("/", " and ")
    raw_words = re.findall(r"[a-z0-9]+", text)
    words = []
    for word in raw_words:
        if word.isdigit() or word in IGNORE:
            continue
        words.append(TOKEN_ALIASES.get(word, word))
    if not words:
        return ("literal", " ".join(raw_words))
    return ("ingredients", tuple(sorted(set(words))))


def universe_values():
    with (ROOT / "universes" / "medicine.tsv").open(encoding="utf-8") as handle:
        return [row["value"] for row in csv.DictReader(handle, delimiter="\t")]


def salience_values():
    out = {}
    with (ROOT / "salience" / "medicine.tsv").open(encoding="utf-8") as handle:
        for row in csv.DictReader(handle, delimiter="\t"):
            try:
                out[row["concept_id"]] = int(float(row.get("pageviews_12m") or 0))
            except ValueError:
                out[row["concept_id"]] = 0
    return out


def build_rows(old_rows):
    values = universe_values()
    by_key = {}
    for value in values:
        key = name_key(value)
        if key in by_key and by_key[key] != value:
            raise SystemExit(f"universe key collision: {by_key[key]} / {value}")
        by_key[key] = value
    salience = salience_values()
    payload = json.loads(MANIFEST.read_text(encoding="utf-8"))
    rows = []
    for item in payload:
        official, seen = [], set()
        for record in item["official"]:
            term = record["term"]
            key = name_key(term)
            if not key[1] if key[0] == "literal" else not key[1]:
                continue
            if key in seen:
                continue
            seen.add(key)
            official.append((term, key))
        members, outside = [], []
        for term, key in official:
            value = by_key.get(key)
            if value is None:
                outside.append(term.lower())
            elif value not in members:
                members.append(value)
        members.sort()
        outside = sorted(set(outside))
        if len(members) < 5:
            raise SystemExit(f"{item['id']}: only {len(members)} universe members")
        if len(members) > len(values) // 2:
            raise SystemExit(f"{item['id']}: {len(members)} members exceeds half the universe")
        if len(members) + len(outside) != len(official):
            raise SystemExit(f"{item['id']}: count mismatch {len(members)} + {len(outside)} != {len(official)}")
        rows.append({
            "id": item["id"], "name": item["name"], "synonyms": [], "members": members,
            "disputed": [], "changes": [], "official_count": len(official),
            "out_of_universe": outside, "source": item["source"],
            "salience": salience.get(item["id"], 0),
        })
    all_rows = old_rows + rows
    sets = {row["id"]: frozenset(row["members"]) for row in all_rows}
    for row in rows:
        target = sets[row["id"]]
        evidence = []
        for member in target:
            others = sorted(lid for lid, members in sets.items()
                            if lid != row["id"] and members != target and member in members)
            if len(others) >= 2:
                evidence.append((member, others))
        if not evidence:
            raise SystemExit(f"{row['id']}: no member belongs to two other distinct lists")
        member, others = evidence[0]
        print(f"overlap {row['id']}: {member} -> {', '.join(others[:3])}")
    return rows


def main():
    path = ROOT / "lists" / "medicine.yaml"
    text = path.read_text(encoding="utf-8")
    if MARK_PREFIX in text:
        text = text[:text.index(MARK_PREFIX)].rstrip() + "\n"
    old_rows = yaml.safe_load(text) or []
    if len(old_rows) != 47:
        raise SystemExit(f"expected 47 existing lists, got {len(old_rows)}")
    rows = build_rows(old_rows)
    block = MARK + "\n" + yaml.safe_dump(rows, allow_unicode=True, sort_keys=False)
    path.write_text(text + block, encoding="utf-8")
    print(f"lists/medicine.yaml: {len(rows)} rows appended")
    for row in rows:
        print(f"{row['id']}\tmembers={len(row['members'])}\tofficial={row['official_count']}")


if __name__ == "__main__":
    main()
